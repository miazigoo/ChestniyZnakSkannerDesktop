def normalize_language(value: str | None) -> str:
    """Возвращает поддерживаемый код языка."""

    token = (value or "").strip().lower().replace("_", "-")
    if token.startswith("ru"):
        return "ru"
    if token.startswith("en"):
        return "en"
    if token.startswith("zh"):
        return "zh"
    return DEFAULT_LANGUAGE


def set_current_language(value: str | None) -> None:
    """Sets the process-wide UI language for newly created widgets."""

    global _current_language
    _current_language = normalize_language(value)


def current_language() -> str:
    """Возвращает текущий язык UI процесса."""

    return _current_language


def tr(key: str, **params: object) -> str:
    """Returns a localized UI string."""

    template = _MESSAGES.get(_current_language, _MESSAGES[DEFAULT_LANGUAGE]).get(
        key,
        _MESSAGES[DEFAULT_LANGUAGE].get(key, key),
    )
    if not params:
        return template
    return template.format(**params)


def translation_key_for_text(text: str) -> str | None:
    """Возвращает ключ локализации для статического текста UI."""

    if not text:
        return None
    for messages in _MESSAGES.values():
        for key, value in messages.items():
            if "{" in value or "}" in value:
                continue
            if value == text:
                return key
    return None


def accept_language(value: str | None) -> str:
    """Возвращает значение Accept-Language для backend negotiation."""

    language = normalize_language(value)
    if language == "ru":
        return "ru-RU,ru;q=0.9,en;q=0.6"
    if language == "zh":
        return "zh-CN,zh;q=0.9,en;q=0.6"
    return "en-US,en;q=0.9,ru;q=0.6"


def language_headers(value: str | None) -> dict[str, str]:
    """Возвращает заголовки локализации для HTTP API."""

    language = normalize_language(value)
    return {
        "X-App-Language": language,
        "X-Language": language,
        "Accept-Language": accept_language(language),
    }
